//! Эталонный генератор A/V-синхронизации (§17.4): окно мигает белым и одновременно звучит щелчок
//! 1 кГц, оба события привязаны к одному моменту мастер-часов QPC.
//!
//! * Видео: выбирается кадровая развёртка монитора (vblank) ~3 кадра вперёд, белый кадр
//!   подаётся так, чтобы показаться в неё; фактическое время показа берётся из статистики
//!   swapchain (`GetFrameStatistics`).
//! * Звук: WASAPI shared; время воспроизведения каждого сэмпла вычисляется по часам устройства
//!   (`IAudioClock::GetPosition`), щелчок ставится сэмпл-в-сэмпл на тот же момент QPC.
//! * Интервалы между событиями неравные (1000 + 50·(k mod 4) мс) — по ним анализатор однозначно
//!   сопоставляет события записи с журналом генератора.
//!
//! Журнал (`--out events.json`): для каждого события — время звука и показа кадра (с от старта).
//! Использование: `syncgen [--seconds 30] [--x 200 --y 200] [--out events.json]`.

#![cfg_attr(not(windows), allow(unused))]

#[cfg(windows)]
mod imp;

fn main() {
    #[cfg(windows)]
    if let Err(e) = imp::run() {
        eprintln!("syncgen: {e}");
        std::process::exit(1);
    }
}
